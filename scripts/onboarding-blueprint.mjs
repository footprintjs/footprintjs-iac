import { createHash } from 'node:crypto';
import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join, relative } from 'node:path';
import { ONBOARDING_STAGE_IDS } from '../src/onboarding/types.ts';
import { ONBOARDING_STAGE_LABELS } from '../src/onboarding/data.ts';

// Development context only: source inventory is never runtime causal evidence.
const root = fileURLToPath(new URL('../', import.meta.url));
const folder = join(root, 'src/onboarding');
const paths = (await readdir(folder)).filter(name => name.endsWith('.ts')).sort().map(name => `src/onboarding/${name}`);
const roles = {
  'types.ts': 'Public stage catalog and adapter contracts',
  'data.ts': 'Bounded public data admission and stage labels',
  'preset.ts': 'Provider-free immutable adapter registration',
  'checks.ts': 'Compose registered check policies without dropping required outcomes',
  'binding.ts': 'Immutable binding provenance; never permission to switch state directories',
  'create-onboarding-chart.ts': 'The native bind → selected action → retain chart construction',
  'workflow.ts': 'Durable action admission, exact review ownership and orchestration',
  'stages.ts': 'Measured stage behavior and delegation to the registered deployment strategy',
  'store.ts': 'Private durable ledger and process lock',
  'recording.ts': 'Retained native recording admission and read-only replay',
  'permissions.ts': 'Allowed next actions derived from admitted state',
  'state.ts': 'Private ledger and receipt contracts',
  'scope.ts': 'Native tracked scope',
  'index.ts': 'Provider-free public entrypoint',
  'node.ts': 'Node-only workflow entrypoint',
};
const sources = await Promise.all(paths.map(async path => ({
  path, sha256: createHash('sha256').update(await readFile(join(root, path))).digest('hex'),
  role: roles[path.split('/').at(-1)] ?? 'Read this module for its owning behavior',
})));
const blueprint = {
  schema: 'infrachart-onboarding-source-context/v1',
  scope: 'Reusable onboarding module only; deployment engines, provider internals and consumer callbacks are separate scopes',
  evidence: 'Declared source inventory. Hashes detect freshness; they do not prove runtime execution or correctness.',
  stages: ONBOARDING_STAGE_IDS.map(id => ({ id, label: ONBOARDING_STAGE_LABELS[id] })),
  chart: { source: 'src/onboarding/create-onboarding-chart.ts', perAction: ['bind', 'selected-action', 'retain'],
    authority: 'workflow.ts admits one manual action; deployment strategy owns plan/apply/reconcile' },
  sources,
  opaqueBoundaries: ['registered discovery/configuration/verification callbacks', 'registered deployment strategy and its native engine', 'provider transport and external application state'],
};
const markdown = `# Onboarding source map\n\nGenerated by \`npm run context:onboarding\`; freshness check: \`npm run context:onboarding:check\`.\n\nThis is a source navigation map. Actual execution, selected paths, outcomes and backwalk require retained native recordings. Read source freely when this inventory is insufficient.\n\n${blueprint.stages.map(stage => stage.label).join(' → ')}. Human actions separate these stages. One native chart records each admitted action; this map does not claim they execute automatically or in parallel.\n\n| Source | Ownership |\n| --- | --- |\n${sources.map(row => `| [${row.path}](../../${row.path}) | ${row.role} |`).join('\n')}\n\n[Exact source hashes](blueprint.json). [Usage and change guidance](../agent-onboarding.md).\n\nExternal callbacks and provider behavior remain explicit boundaries. A missing or unreadable receipt is unknown, never green. Source hashes cannot establish that a provider accepted a change.\n`;
await mkdir(join(root, 'docs/onboarding'), { recursive: true });
for (const [name, content] of [['blueprint.json', JSON.stringify(blueprint, null, 2) + '\n'], ['README.md', markdown]]) {
  const path = join(root, 'docs/onboarding', name);
  if (process.argv.includes('--check')) {
    const saved = await readFile(path, 'utf8').catch(error => { if (error.code === 'ENOENT') return undefined; throw error; });
    if (saved !== content) throw Error(`Stale onboarding context: ${relative(root, path)}. Run npm run context:onboarding.`);
  } else await writeFile(path, content);
}
console.log(process.argv.includes('--check') ? 'Onboarding source context is current.' : 'Generated onboarding source context.');
